export function getCouponsForRegion(region: 'india' | 'us'): Coupon[] {
  return coupons.filter((c) => c.region === region || c.region === 'both');
}

export function getActiveBankOffers(): BankWeekend[] {
  const now = new Date();
  const dayOfMonth = now.getDate();
  if (dayOfMonth <= 7) return bankWeekends.filter((b) => b.weekend === '1st Weekend');
  if (dayOfMonth <= 14) return bankWeekends.filter((b) => b.weekend === '2nd Weekend');
  if (dayOfMonth <= 21) return bankWeekends.filter((b) => b.weekend === '3rd Weekend');
  return bankWeekends.filter((b) => b.weekend === '4th Weekend');
}
